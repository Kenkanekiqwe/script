function emsg(message) {
    new Noty({
        type: 'error',
        layout: 'topCenter',
        theme: 'metroui',
        text: message,
        timeout: '5000',
        progressBar: true,
        animation: {
            open: 'noty_effects_open',
            close: 'noty_effects_close'
        }
    }).show();
}


